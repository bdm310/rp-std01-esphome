#!/usr/bin/env python3
"""Turn the linked MCU programs and the firmware headers into what ESPHome needs.

Reads <build>/app.ihx and <build>/boot.ihx (make firmware) and firmware/include, and writes:
- <build>/full.ihx: bootloader and application, for the first flash through STC's bootloader by
  stcgal with the box open;
- esphome/components/rpstd01_tool/rpstd01_mcu_full_image.h: the same image as a C++ array, which
  the MCU tool installs;
- esphome/components/rpstd01_link/rpstd01_fw_constants.h: every #define in HEADERS as a C++
  constant, and the image's version, build ID and bootloader version (MCU_IMAGE_*).

A file is written only when its contents change, so ESPHome does not rebuild for nothing. With
--check nothing is written, and it fails if a committed ESPHome header differs from what it would
write, or if the bootloader or the application differs from the image in the latest git tag (the
last release) without a higher BOOT_VERSION or FW_VERSION. Before the first tag versions are free.
"""

from __future__ import annotations

import argparse
import functools
import hashlib
import os
from pathlib import Path
import re
import shlex
import struct
import subprocess
import sys
import tempfile
from typing import NamedTuple
import zlib

FIRMWARE = Path(__file__).resolve().parent.parent
REPO = FIRMWARE.parent
HEADERS = ("protocol.h", "flashmap.h", "board.h")
COMPONENTS = REPO / "esphome" / "components"
IMAGE_H = "rpstd01_tool/rpstd01_mcu_full_image.h"
CONSTANTS_H = "rpstd01_link/rpstd01_fw_constants.h"
GENERATED = "// Generated by firmware/tools/mkesphome.py (make firmware). Do not edit."

DEFINE = re.compile(r"#define\s+(\w+)\s+(.*)$")
COMMENT = re.compile(r"/\*.*?\*/")
HEX = re.compile(r"0[xX]([0-9A-Fa-f]+)[uUlL]*")

CONSTANTS_PROGRAM = r"""#include <stdio.h>
{includes}
static void text(const char *name, const char *value) {{ printf("%s s %s\n", name, value); }}
static void sig(const char *name, long long value) {{ printf("%s i %lld\n", name, value); }}
static void uns(const char *name, unsigned long long value) {{ printf("%s u %llu\n", name, value); }}
#define SHOW(name) \
  _Generic((name), char *: text, unsigned: uns, unsigned long: uns, unsigned long long: uns, \
           default: sig)(#name, (name))
int main(void) {{
{shows}
  return 0;
}}
"""


class Define(NamedTuple):
    name: str
    text: str


class Constant(NamedTuple):
    value: int | str
    unsigned: bool


def without_comments(name: str, rest: str) -> str:
    value = COMMENT.sub("", rest).strip()
    if "/*" in value:
        raise ValueError(f"{name}: comment not closed on its line")
    return value


def read_defines(text: str) -> list[Define]:
    """Each object-like #define with a value, in order."""
    out = []
    for line in text.splitlines():
        m = DEFINE.match(line.strip())
        if not m:
            continue
        name, rest = m.groups()
        value = without_comments(name, rest)
        if value:
            out.append(Define(name, value))
    return out


def header_defines(include: Path = FIRMWARE / "include") -> list[Define]:
    return [d for name in HEADERS for d in read_defines((include / name).read_text())]


def constants_program() -> str:
    """C source that prints each define of HEADERS as "name kind value", one per line, kind s for a
    string, u for an unsigned and i for a signed number."""
    return CONSTANTS_PROGRAM.format(
        includes="\n".join(f'#include "{name}"' for name in HEADERS),
        shows="\n".join(f"  SHOW({d.name});" for d in header_defines()),
    )


def host_compiler() -> list[str]:
    return shlex.split(os.environ.get("CC", "cc"))


@functools.cache
def evaluated() -> dict[str, Constant]:
    """Every define of HEADERS, by name, as the host's C compiler evaluates it."""
    with tempfile.TemporaryDirectory() as tmp:
        source, program = Path(tmp) / "constants.c", Path(tmp) / "constants"
        source.write_text(constants_program())
        cc = [*host_compiler(), "-std=c11", "-Wall", "-Werror", "-iquote", str(FIRMWARE / "include")]
        built = subprocess.run([*cc, str(source), "-o", str(program)], capture_output=True, text=True)
        if built.returncode:
            raise ValueError(f"cannot build the constants program:\n{built.stderr}")
        out = subprocess.run([str(program)], capture_output=True, text=True, check=True).stdout
    values: dict[str, Constant] = {}
    for line in out.splitlines():
        name, kind, value = line.split(" ", 2)
        values[name] = Constant(value, False) if kind == "s" else Constant(int(value), kind == "u")
    return values


def constants() -> dict[str, int | str]:
    return {name: c.value for name, c in evaluated().items()}


def numbers() -> dict[str, int]:
    return {name: value for name, value in constants().items() if isinstance(value, int)}


def sdcc_check() -> str:
    """C source that SDCC compiles only if it gives every constant the value constants() has."""
    lines = [f'#include "{name}"' for name in HEADERS]
    for name, value in numbers().items():
        literal = f"{value}l" if value < 0 else f"{value}ul"
        lines.append(f'_Static_assert(({name}) == {literal}, "{name} is not {value} on the MCU");')
    return "\n".join(lines) + "\n"


def make_variables() -> str:
    """The constants as Makefile variables, FWC_<name>."""
    return "".join(f"FWC_{name} := {value}\n" for name, value in numbers().items())


class Layout(NamedTuple):
    app_base: int
    app_end: int
    app_size: int
    trailer_size: int
    boot_version_addr: int
    magic: bytes
    tr_magic: int
    tr_code_len: int
    tr_crc: int
    tr_version: int
    tr_build: int
    tr_valid: int

    @property
    def trailer(self) -> int:
        """The trailer's offset in the application area."""
        return self.app_size - self.trailer_size

    @property
    def valid(self) -> int:
        """The valid mark's offset in the application area."""
        return self.trailer + self.tr_valid


@functools.cache
def layout() -> Layout:
    c = constants()
    names = [f for f in Layout._fields if f != "magic"]
    return Layout(**{f: c[f.upper()] for f in names}, magic=str(c["APP_MAGIC"]).encode())


def crc16(data: bytes) -> int:
    """CRC-16/CCITT-FALSE, as in common/crc16.c."""
    crc = constants()["CRC16_INIT"]
    for byte in data:
        crc ^= byte << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) if crc & 0x8000 else crc << 1
            crc &= 0xFFFF
    return crc


class Trailer(NamedTuple):
    magic: bytes
    code_len: int
    crc: int
    version: int
    build: int
    valid: int


def parse_trailer(area: bytes) -> Trailer:
    """The trailer at the end of an application area (APP_SIZE bytes)."""
    fm = layout()
    if len(area) != fm.app_size:
        raise ValueError(f"application area is {len(area)} bytes, expected {fm.app_size}")
    t = area[fm.trailer :]
    magic = t[fm.tr_magic : fm.tr_magic + len(fm.magic)]
    (code_len,) = struct.unpack_from("<H", t, fm.tr_code_len)
    (crc,) = struct.unpack_from("<H", t, fm.tr_crc)
    (version,) = struct.unpack_from("<H", t, fm.tr_version)
    (build,) = struct.unpack_from("<I", t, fm.tr_build)
    return Trailer(magic, code_len, crc, version, build, t[fm.tr_valid])


def read_ihex(path: Path) -> dict[int, int]:
    """Return {address: byte} for the data records of an Intel HEX file."""
    mem: dict[int, int] = {}
    upper = 0
    for lineno, line in enumerate(path.read_text().splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        if not line.startswith(":"):
            raise ValueError(f"{path}:{lineno}: not an Intel HEX record")
        rec = bytes.fromhex(line[1:])
        if sum(rec) & 0xFF:
            raise ValueError(f"{path}:{lineno}: bad checksum")
        count, addr, kind = rec[0], (rec[1] << 8) | rec[2], rec[3]
        data = rec[4 : 4 + count]
        if kind == 0:
            for i, b in enumerate(data):
                mem[upper + addr + i] = b
        elif kind == 1:
            break
        elif kind == 4:
            upper = int.from_bytes(data, "big") << 16
        else:
            raise ValueError(f"{path}:{lineno}: unsupported record type {kind}")
    return mem


def render_ihex(image: bytes) -> str:
    """image from address 0 as 16-byte records, skipping runs that are all 0xFF."""
    lines = []
    for addr in range(0, len(image), 16):
        chunk = image[addr : addr + 16]
        if all(b == 0xFF for b in chunk):
            continue
        rec = bytes([len(chunk), addr >> 8, addr & 0xFF, 0]) + chunk
        lines.append(":" + (rec + bytes([(-sum(rec)) & 0xFF])).hex().upper())
    lines.append(":00000001FF")
    return "\n".join(lines) + "\n"


def build_app(app: dict[int, int], version: int, build: int) -> bytes:
    """The update image (APP_SIZE bytes) with its trailer, valid mark 0xFF."""
    fm = layout()
    if not app:
        raise ValueError("application image is empty")
    lo, hi = min(app), max(app)
    if lo < fm.app_base or hi >= fm.app_base + fm.trailer:
        raise ValueError(
            f"application uses 0x{lo:04X}-0x{hi:04X}, outside 0x{fm.app_base:04X}-"
            f"0x{fm.app_base + fm.trailer - 1:04X}"
        )
    image = bytearray(b"\xff" * fm.app_size)
    for addr, b in app.items():
        image[addr - fm.app_base] = b
    code_len = hi + 1 - fm.app_base
    t = fm.trailer
    image[t + fm.tr_magic : t + fm.tr_magic + len(fm.magic)] = fm.magic
    struct.pack_into("<H", image, t + fm.tr_code_len, code_len)
    struct.pack_into("<H", image, t + fm.tr_crc, crc16(bytes(image[:code_len])))
    struct.pack_into("<H", image, t + fm.tr_version, version)
    struct.pack_into("<I", image, t + fm.tr_build, build)
    return bytes(image)


def build_id(app_image: bytes, version: int) -> int:
    """The first 4 bytes of a SHA-256 over the application area, without its trailer, and the
    version."""
    h = hashlib.sha256()
    h.update(app_image[: layout().trailer])
    h.update(struct.pack("<H", version))
    return int.from_bytes(h.digest()[:4], "big")


def build_full(boot: dict[int, int], app_image: bytes) -> bytes:
    """Bootloader plus application from address 0, valid mark 0x00."""
    fm = layout()
    if not boot:
        raise ValueError("bootloader image is empty")
    if max(boot) >= fm.app_base:
        raise ValueError(f"bootloader reaches 0x{max(boot):04X}, beyond 0x{fm.app_base - 1:04X}")
    if boot.get(fm.boot_version_addr, 0xFF) == 0xFF:
        raise ValueError(f"bootloader has no version byte at 0x{fm.boot_version_addr:04X}")
    full = bytearray(b"\xff" * fm.app_end)
    for addr, b in boot.items():
        full[addr] = b
    full[fm.app_base : fm.app_end] = app_image
    full[fm.app_base + fm.valid] = 0x00
    return bytes(full)


def app_area(full: bytes) -> bytes:
    """The update image in a full image: its application area, valid mark 0xFF."""
    fm = layout()
    area = bytearray(full[fm.app_base : fm.app_end])
    area[fm.valid] = 0xFF
    return bytes(area)


def build_images(app: dict[int, int], boot: dict[int, int], version: int) -> bytes:
    """The full image, with the build ID made from the application."""
    build = build_id(build_app(app, version, 0), version)
    return build_full(boot, build_app(app, version, build))


def render_image_header(full: bytes) -> str:
    lines = [
        GENERATED,
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace rpstd01 {",
        "",
        f"inline constexpr uint32_t MCU_IMAGE_CRC32 = 0x{zlib.crc32(full):08X}u;",
        f"inline constexpr uint8_t MCU_IMAGE[{len(full)}] = {{",
    ]
    for off in range(0, len(full), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in full[off : off + 16]) + ",")
    lines += ["};", "", "}", ""]
    return "\n".join(lines)


def image_from_header(text: str) -> bytes:
    """The full image in a header written by render_image_header()."""
    body = text.split("MCU_IMAGE[", 1)[1].split("{", 1)[1].split("}", 1)[0]
    return bytes(int(v, 16) for v in re.findall(r"0x([0-9A-F]{2})", body))


def read_image_header(path: Path = COMPONENTS / IMAGE_H) -> bytes:
    return image_from_header(path.read_text())


def released_image(path: Path) -> tuple[str, bytes] | None:
    """The latest git tag and the full image in the header at path as that tag has it, or None
    before the first release or outside git."""

    def git(*args: str) -> subprocess.CompletedProcess:
        return subprocess.run(["git", "-C", str(path.parent), *args], capture_output=True, text=True)

    try:
        tag = git("describe", "--tags", "--abbrev=0")
    except FileNotFoundError:
        return None
    if tag.returncode != 0:
        return None
    release = tag.stdout.strip()
    shown = git("show", f"{release}:./{path.name}")
    return (release, image_from_header(shown.stdout)) if shown.returncode == 0 else None


def defined_in(define: str) -> str:
    return next(
        f"firmware/include/{name}"
        for name in HEADERS
        if any(d.name == define for d in read_defines((FIRMWARE / "include" / name).read_text()))
    )


def missing_bumps(old: bytes, new: bytes) -> list[str]:
    """What changed from the full image old to new without a higher version that says so."""
    out = []
    at = layout().boot_version_addr

    def boot_code(full: bytes) -> bytes:
        return full[:at] + full[at + 1 : layout().app_base]

    if boot_code(old) != boot_code(new) and new[at] <= old[at]:
        out.append(f"the bootloader changed: raise BOOT_VERSION above {old[at]} in {defined_in('BOOT_VERSION')}")
    old_app, new_app = parse_trailer(app_area(old)), parse_trailer(app_area(new))
    if old_app.build != new_app.build and new_app.version <= old_app.version:
        out.append(
            f"the application changed: raise FW_VERSION above 0x{old_app.version:04X} in {defined_in('FW_VERSION')}"
        )
    return out


# Values that fill a field of fixed width, whatever their current value.
FIXED_TYPES = {"FW_VERSION": "uint16_t"}


def cpp_type(c: Constant) -> str:
    """For an unsigned value the smallest of uint8_t, uint16_t and uint32_t that holds it, so that it
    promotes to int in mixed arithmetic like the byte and word fields it is used with."""
    if not isinstance(c.value, int):
        raise ValueError(f"{c.value}: not a number")
    if not c.unsigned:
        return "int"
    for bits in (8, 16, 32):
        if c.value < 1 << bits:
            return f"uint{bits}_t"
    raise ValueError(f"{c.value}: too large")


def cpp_constant(define: Define, c: Constant) -> str:
    if isinstance(c.value, str):
        return f'inline constexpr char {define.name}[] = "{c.value}";'
    hex_digits = HEX.fullmatch(define.text)
    if hex_digits:
        literal = f"0x{c.value:0{len(hex_digits.group(1))}X}"
    else:
        literal = str(c.value)
    suffix = "u" if c.unsigned else ""
    return f"inline constexpr {FIXED_TYPES.get(define.name) or cpp_type(c)} {define.name} = {literal}{suffix};"


def render_constants_header(full: bytes) -> str:
    trailer = parse_trailer(app_area(full))
    values = evaluated()
    lines = [GENERATED, "#pragma once", "", "#include <cstdint>", "", "namespace rpstd01 {", ""]
    lines += [cpp_constant(d, values[d.name]) for d in header_defines()]
    lines += [
        f"inline constexpr uint16_t MCU_IMAGE_VERSION = 0x{trailer.version:04X}u;",
        f"inline constexpr uint32_t MCU_IMAGE_BUILD = 0x{trailer.build:08X}u;",
        f"inline constexpr uint8_t MCU_IMAGE_BOOT_VERSION = {full[layout().boot_version_addr]}u;",
        "",
        "}",
        "",
    ]
    return "\n".join(lines)


def esphome_headers(full: bytes) -> dict[str, str]:
    return {IMAGE_H: render_image_header(full), CONSTANTS_H: render_constants_header(full)}


def write_if_changed(path: Path, text: str) -> None:
    if path.exists() and path.read_text() == text:
        return
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text)
    tmp.replace(path)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--build", type=Path, help="folder with app.ihx and boot.ihx")
    parser.add_argument("--components", type=Path, default=COMPONENTS, help="ESPHome components folder")
    parser.add_argument("--check", action="store_true", help="compare with the headers, write nothing")
    parser.add_argument("--make", action="store_true", help="print the constants as Makefile variables")
    parser.add_argument("--sdcc-check", action="store_true", help="print the constants as SDCC static asserts")
    args = parser.parse_args(argv)
    if args.make:
        print(make_variables(), end="")
        return 0
    if args.sdcc_check:
        print(sdcc_check(), end="")
        return 0
    if not args.build:
        parser.error("--build is required")

    try:
        app, boot = read_ihex(args.build / "app.ihx"), read_ihex(args.build / "boot.ihx")
        full = build_images(app, boot, numbers()["FW_VERSION"])
        headers = esphome_headers(full)
    except ValueError as err:
        print(f"mkesphome: {err}", file=sys.stderr)
        return 1

    if args.check:
        stale = [name for name, text in headers.items() if (args.components / name).read_text() != text]
        for name in stale:
            print(f"{args.components / name} does not match the firmware: run make firmware and commit it")
        released = released_image(args.components / IMAGE_H)
        bumps = missing_bumps(released[1], full) if released else []
        for bump in bumps:
            print(f"Since release {released[0]} {bump}")
        return 1 if stale or bumps else 0

    write_if_changed(args.build / "full.ihx", render_ihex(full))
    for name, text in headers.items():
        write_if_changed(args.components / name, text)
    fm = layout()
    trailer = parse_trailer(app_area(full))
    boot_end = max(a for a in boot if a != fm.boot_version_addr) + 1
    print(
        f"bootloader v{full[fm.boot_version_addr]} {boot_end} of {fm.boot_version_addr} bytes, application "
        f"{trailer.code_len} of {fm.trailer} bytes, version {trailer.version:04X}, build {trailer.build:08X}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
